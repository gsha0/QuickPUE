def eu(s, keys):
    tot = 0.0
    for k in keys.split("+"):
        tot += float(s.end_uses[s.end_uses.key == k].kwh.sum()) / 1e3
    return tot


def fmt(v, d=1):
    return f"{v:,.{d}f}"


